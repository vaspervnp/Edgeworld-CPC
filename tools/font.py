#!/usr/bin/env python3
"""The 3x5 pixel font of the HUD and the game's text, 4 pixels per character.

Run as a script, writes the font for the game: 5 bytes per character from
ASCII 32 to 95, one per pixel row, the 3 pixels in bits 7, 6 and 5.

Usage: font.py out.bin
"""
import sys

FIRST, LAST = 32, 95
ADVANCE = 4

FONT = {
    " ": ["000"] * 5,
    "0": ["111", "101", "101", "101", "111"], "1": ["010", "110", "010", "010", "111"],
    "2": ["111", "001", "111", "100", "111"], "3": ["111", "001", "011", "001", "111"],
    "4": ["101", "101", "111", "001", "001"], "5": ["111", "100", "111", "001", "111"],
    "6": ["111", "100", "111", "101", "111"], "7": ["111", "001", "010", "010", "010"],
    "8": ["111", "101", "111", "101", "111"], "9": ["111", "101", "111", "001", "111"],
    "A": ["010", "101", "111", "101", "101"], "B": ["110", "101", "110", "101", "110"],
    "C": ["011", "100", "100", "100", "011"], "D": ["110", "101", "101", "101", "110"],
    "E": ["111", "100", "110", "100", "111"], "F": ["111", "100", "110", "100", "100"],
    "G": ["111", "100", "101", "101", "111"], "H": ["101", "101", "111", "101", "101"],
    "I": ["111", "010", "010", "010", "111"], "J": ["001", "001", "001", "101", "111"],
    "K": ["101", "101", "110", "101", "101"], "L": ["100", "100", "100", "100", "111"],
    "M": ["101", "111", "111", "101", "101"], "N": ["111", "101", "101", "101", "101"],
    "O": ["111", "101", "101", "101", "111"], "P": ["111", "101", "111", "100", "100"],
    "Q": ["010", "101", "101", "110", "011"], "R": ["110", "101", "110", "101", "101"],
    "S": ["111", "100", "111", "001", "111"], "T": ["111", "010", "010", "010", "010"],
    "U": ["101", "101", "101", "101", "111"], "V": ["101", "101", "101", "101", "010"],
    "W": ["101", "101", "111", "111", "101"], "X": ["101", "101", "010", "101", "101"],
    "Y": ["101", "101", "010", "010", "010"], "Z": ["111", "001", "010", "100", "111"],
    ":": ["000", "010", "000", "010", "000"], "!": ["010", "010", "010", "000", "010"],
    ".": ["000", "000", "000", "000", "010"], ",": ["000", "000", "000", "010", "100"],
    "-": ["000", "000", "111", "000", "000"], "+": ["000", "010", "111", "010", "000"],
    "'": ["010", "010", "000", "000", "000"], "/": ["001", "001", "010", "100", "100"],
    "?": ["111", "001", "011", "000", "010"], ">": ["100", "010", "001", "010", "100"],
    "<": ["001", "010", "100", "010", "001"], "_": ["000", "000", "000", "000", "111"],
    "=": ["000", "111", "000", "111", "000"],
}


def glyph(ch):
    return FONT.get(ch, FONT[" "])


def draw(px, x, y, s, pen):
    """Draw string s at (x, y) into a PIL pixel access object, pen on, others untouched."""
    for ch in s:
        for gy, row in enumerate(glyph(ch)):
            for gx, bit in enumerate(row):
                if bit == "1":
                    px[x + gx, y + gy] = pen
        x += ADVANCE


def rows(s, pen, bg=0):
    """String s as 5 lists of pens (background bg), ADVANCE pixels per character."""
    out = [[] for _ in range(5)]
    for ch in s:
        for gy, row in enumerate(glyph(ch)):
            out[gy] += [pen if b == "1" else bg for b in row] + [bg]
    return out


def main(out):
    data = bytearray()
    for code in range(FIRST, LAST + 1):
        for row in glyph(chr(code)):
            data.append(int(row, 2) << 5)
    open(out, "wb").write(data)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
